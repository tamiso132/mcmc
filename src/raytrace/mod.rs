//! The public API for the Sparse Voxel Octree (SVO) system.
//!
//! This module provides a safe, idiomatic Rust interface for
//! building and managing the SVO data.
//!
//! ## Workflow
//!
//! 1.  Create a `RaytraceWorld` during your app's initialization.
//! 2.  This internally uses an `SvoBuilder` to insert voxel data.
//! 3.  The builder is consumed to create a final, sorted `SvoTree`.
//! 4.  The `RaytraceWorld` then uploads the `SvoTree` data to GPU buffers.
//! 5.  Pass the `ResourceHandle`s for these buffers to your pipelines.

